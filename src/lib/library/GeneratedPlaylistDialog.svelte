<!--
  The confirmation that an edit changes a generated playlist for good (k19).

  A playlist a listening service generates refreshes every day and expires; the
  first rename, reorder or track change makes it the reader's own, which stops
  both. This dialog states that before the edit runs, because it is a decision
  rather than a destructive confirmation: a regular dialog with Cancel and the
  suggested "Edit Playlist", never `alert`.

  Usage:
  ```
  {#if detachRun !== null}
    <GeneratedPlaylistDialog
      service={generatedBy}
      oncancel={() => (detachRun = null)}
      onconfirm={() => { const run = detachRun; detachRun = null; run?.(); }}
    />
  {/if}
  ```
-->
<script lang="ts">
  import Button from '#lib/ui/Button.svelte';
  import Dialog from '#lib/ui/Dialog.svelte';

  /** Props of the generated-playlist confirmation. */
  interface Props {
    /** The display name of the service that generates the playlist. */
    service: string;
    /** Runs when the reader accepts that the edit detaches the playlist. */
    onconfirm: () => void;
    /** Runs when the reader keeps the playlist as it is. */
    oncancel: () => void;
  }

  let { service, onconfirm, oncancel }: Props = $props();
</script>

<Dialog title="Edit This Playlist?" onclose={oncancel}>
  <p>
    This playlist is generated by {service} and refreshes daily. Editing it makes it yours: it stops refreshing
    and no longer expires.
  </p>

  {#snippet footer()}
    <Button onclick={oncancel}>Cancel</Button>
    <Button variant="suggested" onclick={onconfirm}>Edit Playlist</Button>
  {/snippet}
</Dialog>
