<!--
  The dialog that names a new credential (E-B-2).

  The name is what the listing shows later, so it is the only field: the secret
  is generated by the server and shown once, after this dialog closes. Create is
  disabled while the name is empty and while the call runs; a refused call stays
  in the dialog with the server's sentence above the footer.

  Usage:
  `<CredentialDialog kind="apiKey" onclose={close} oncreated={showSecret} />`
-->
<script lang="ts">
  import { credentialLabels, createApiKey, createAppPassword } from '#lib/account/credentials';
  import type { CredentialKind } from '#lib/account/credentials';
  import Banner from '#lib/ui/Banner.svelte';
  import Button from '#lib/ui/Button.svelte';
  import Dialog from '#lib/ui/Dialog.svelte';
  import FormField from '#lib/ui/FormField.svelte';
  import TextField from '#lib/ui/TextField.svelte';

  /** Props of the dialog. */
  interface Props {
    /** The kind of credential to create. */
    kind: CredentialKind;
    /** Closes the dialog; the caller unmounts it. */
    onclose: () => void;
    /** Receives the created credential, which carries its secret. */
    oncreated: (created: { name: string; secret: string }) => void;
  }

  let { kind, onclose, oncreated }: Props = $props();

  const uid = $props.id();
  const nameId = $derived(`credential-name-${uid}`);
  const formId = $derived(`credential-form-${uid}`);
  const labels = $derived(credentialLabels(kind));

  let name = $state('');
  let failure = $state<string | null>(null);
  let busy = $state(false);

  /**
   * Creates the credential under the typed name.
   *
   * @param event The form submission.
   */
  async function create(event: SubmitEvent): Promise<void> {
    event.preventDefault();
    const trimmed = name.trim();
    if (trimmed === '') {
      failure = 'Choose a name.';
      return;
    }
    busy = true;
    const result =
      kind === 'apiKey' ? await createApiKey(trimmed) : await createAppPassword(trimmed);
    busy = false;
    if (!result.ok) {
      failure = result.message;
      return;
    }
    oncreated({ name: result.value.name, secret: result.value.secret });
  }
</script>

{#snippet footer()}
  <Button onclick={onclose}>Cancel</Button>
  <Button variant="suggested" type="submit" form={formId} {busy} disabled={busy || name === ''}>
    Create
  </Button>
{/snippet}

<Dialog title={labels.create} {onclose} {footer}>
  <form id={formId} class="hs-form" novalidate onsubmit={create}>
    <FormField label="Name" for={nameId}>
      <TextField id={nameId} bind:value={name} autocomplete="off" />
    </FormField>

    {#if failure !== null}
      <Banner level="error" text={failure} />
    {/if}
  </form>
</Dialog>
